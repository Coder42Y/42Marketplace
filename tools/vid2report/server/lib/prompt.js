/**
 * Prompt templates for video content analysis.
 */

function buildPrompt(title, transcript, sourceUrl) {
  const isShort = transcript.length < 500

  return `你是一位专业的内容分析师，请对以下视频内容进行深度分析，生成一份结构化的研究报告。

视频标题：${title}
视频来源：${sourceUrl}

${isShort ? '⚠️ 注意：当前提供的文案是视频的简介/概要，内容较短。请基于简介内容进行分析，不要编造视频中未提及的细节。如果某些部分缺乏具体信息，请实事求是地标注，不要自行补全。' : ''}

完整文案：
${transcript}

请按以下结构输出（Markdown 格式）：

## 概述
用 2-3 句话概括视频的核心内容和主旨。

## 核心主题
按视频推进顺序，拆解每个重要话题。每节一个小标题（### emoji + 标题），下面展开详细阐述。${isShort ? '由于源文案较短，仅基于已有内容展开分析，不要杜撰细节数据。' : '不要遗漏原文中的关键论据、数据、案例。'}

## 关键洞察
提炼 3-5 条有价值的关键洞察或反常识观点。

## 行动建议
基于视频内容，给出具体可操作的实践建议。

## 金句摘录
摘录 3 条原文中最精彩或最有启发性的句子。只摘录原文实际存在的句子，不要编造。

要求：
- 全部用中文输出
- 内容要详细充实，不要省略
- 不要输出任何推理过程，直接出报告
- 不要 <think> 标签
- 金句必须来自原文，不要改写或编造`
}

module.exports = { buildPrompt }
